/**
 * Fórmulas exactas de OpenMU `itemVisualTier.ts` y `itemLegacyEffects.ts`:
 * Brillo +0..+15, gradiente cian-verde para Excellent y esmeralda para Ancient.
 */
export interface ItemVisualSpec {
  tier: number;
  emissiveHex: number;
  emissiveIntensity: number;
  pulseAmplitude: number;
  isExcellent: boolean;
  isAncient: boolean;
  hasSpark: boolean;
  labelColor: string;
}

export function getItemVisualSpec(item?: Pick<MuItem, 'enhanceLevel' | 'rarity'> | null, baseColorHex = 0xf59e0b): ItemVisualSpec {
  const level = item?.enhanceLevel ?? 0;
  const rarity = item?.rarity ?? 'normal';
  const isExcellent = rarity === 'excellent';
  const isAncient = rarity === 'ancient';

  // OpenMU itemVisualTier.ts: +7..+15 progressive glow tier
  const emissiveIntensity =
    level >= 15
      ? 1.55
      : level >= 13
        ? 1.25
        : level >= 11
          ? 0.95
          : level >= 9
            ? 0.72
            : level >= 7
              ? 0.42
              : 0.1;

  // OpenMU itemLegacyEffects.ts: EXC_A [0.2, 0.9, 1.0] <-> EXC_B [0.3, 1.0, 0.45], ANCIENT [0.12, 0.65, 0.28]
  const emissiveHex = isExcellent
    ? 0x33f2b8
    : isAncient
      ? 0x1fa647
      : level >= 13
        ? 0xfbbf24
        : baseColorHex;

  return {
    tier: level,
    emissiveHex,
    emissiveIntensity,
    pulseAmplitude: level >= 9 ? 0.28 : level >= 7 ? 0.14 : 0,
    isExcellent,
    isAncient,
    hasSpark: level >= 11,
    labelColor: isExcellent ? '#34d399' : isAncient ? '#38bdf8' : level >= 9 ? '#fbbf24' : '#e2e8f0',
  };
}

