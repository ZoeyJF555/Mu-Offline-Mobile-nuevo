export interface ItemVisualSpec {
  tier: number;
  emissiveHex: number;
  emissiveIntensity: number;
  pulseAmplitude: number;
  isExcellent: boolean;
  isAncient: boolean;
  hasSpark: boolean;
  labelColor: string;
}

export function getItemVisualSpec(item?: Pick<MuItem, 'enhanceLevel' | 'rarity'> | null, baseColorHex = 0xf59e0b): ItemVisualSpec {
  const level = item?.enhanceLevel ?? 0;
  const rarity = item?.rarity ?? 'normal';
  const isExcellent = rarity === 'excellent';
  const isAncient = rarity === 'ancient';

  const emissiveIntensity =
    level >= 15
      ? 1.55
      : level >= 13
        ? 1.25
        : level >= 11
          ? 0.95
          : level >= 9
            ? 0.72
            : level >= 7
              ? 0.42
              : 0.1;

  const emissiveHex = isExcellent
    ? 0x33f2b8
    : isAncient
      ? 0x1fa647
      : level >= 13
        ? 0xfbbf24
        : baseColorHex;

  return {
    tier: level,
    emissiveHex,
    emissiveIntensity,
    pulseAmplitude: level >= 9 ? 0.28 : level >= 7 ? 0.14 : 0,
    isExcellent,
    isAncient,
    hasSpark: level >= 11,
    labelColor: isExcellent ? '#34d399' : isAncient ? '#38bdf8' : level >= 9 ? '#fbbf24' : '#e2e8f0',
  };
}

